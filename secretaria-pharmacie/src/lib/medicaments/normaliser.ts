/** Normalise une chaîne pour la recherche : minuscule, sans accents, sans ponctuation. */
export function normaliserTexte(input: string): string {
  return input
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}
